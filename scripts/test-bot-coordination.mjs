  requests = [];
  const events = [];
  const sender = { once() {}, isDestroyed: () => false, send: (channel, payload) => events.push(payload) };
  await service.sendMessage({ conversationId: conversation.id, content: 'Compare the proposals' }, sender);
  assert.deepEqual(requests.map(r => r.model), ['Lead', 'Research', 'Check', 'Lead']);
  assert.ok(requests.at(-1).messages.some(m => m.content.includes('Answer Research') && m.content.includes('Answer Check')), 'Final answer receives worker results');
  assert.equal(requests.at(-1).messages.map(m => m.content).join('\n').split('Compare the proposals').length - 1, 1, 'Summary does not repeat the user request as a new instruction');
  assert.ok(events.some(e => e.conversation?.coordinationPhase === 'planning'));
  assert.ok(events.some(e => e.conversation?.coordinationPhase === 'working'));
  assert.equal(service.getConversation(conversation.id).runningRoundId, null);
