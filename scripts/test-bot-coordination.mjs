  api.callChatCompletion = request => {
    if (request.messages.at(-1).content.includes('Act as coordinator.')) return Promise.resolve({ content: JSON.stringify({ mode: 'parallel', tasks: [research, check].map(bot => ({ botId: bot.id, instruction: 'Independent task' })) }), elapsedMs: 1 });
    if (request.model === 'Lead') return normalCall(request);
    return new Promise(resolve => { workers.push({ request, resolve }); if (workers.length === 2) workerStarted(); });
  };
  const parallel = service.sendMessage({ conversationId: conversation.id, content: 'Parallel work' });
  await workerReady;
  assert.equal(workers.length, 2, 'Both workers start before either finishes');
