import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { EventEmitter } from 'node:events';
const require = createRequire(import.meta.url);
const updater = new EventEmitter();
let autoCheck = false, checks = 0;
const preferences = { get: () => autoCheck, set: value => { autoCheck = value; } };
let downloads = 0, installs = 0, busy = false, opened = '';
updater.checkForUpdates = async () => ({ updateInfo: { version: '1.2.0' } });
updater.downloadUpdate = async () => { downloads++; };
updater.quitAndInstall = () => { installs++; };
let release = { tag_name: 'v1.2.0', assets: [{ name: 'latest.yml' }] };
const mockModule = (name, exports) => { const id = require.resolve(name); require.cache[id] = { id, filename: id, loaded: true, exports }; };
mockModule('electron', { app: { isPackaged: true, getVersion: () => '1.1.1' }, net: { fetch: async () => { checks++; return { ok: true, json: async () => release }; } }, shell: { openExternal: async url => { opened = url; } } });
mockModule('electron-updater', { autoUpdater: updater });
const { AppUpdater, isNewerRelease } = require('../dist/main/appUpdater.js');
assert.equal(isNewerRelease('v1.10.0', '1.9.9'), true);
assert.equal(isNewerRelease('1.1.1', '1.1.1'), false);
assert.equal(isNewerRelease('1.2.0-beta', '1.1.1'), false);
const platform = Object.getOwnPropertyDescriptor(process, 'platform');
try {
  Object.defineProperty(process, 'platform', { value: 'win32' });
  const service = new AppUpdater(() => busy, preferences);
  await service.checkOnStartup(); assert.equal(checks, 0, 'Unchecked startup makes no request');
  assert.equal((await service.action('enable-auto-check')).autoCheck, true);
  await service.checkOnStartup(); assert.equal(checks, 1);
  await service.action('disable-auto-check');
  await service.checkOnStartup(); assert.equal(checks, 1, 'Disabled startup makes no request');
  assert.equal(updater.autoDownload, false);
  assert.equal(updater.autoInstallOnAppQuit, false);
  assert.equal((await service.action('check')).canInstall, true);
  assert.equal(downloads, 0, 'Checking never downloads');
  await service.action('download'); await service.action('download');
  assert.equal(downloads, 1, 'Duplicate download clicks ignored');
  updater.emit('update-downloaded');
  busy = true;
  assert.equal((await service.action('install')).error, 'busy'); assert.equal(installs, 0);
  busy = false; await service.action('install'); assert.equal(installs, 1);
  Object.defineProperty(process, 'platform', { value: 'darwin' });
  const mac = new AppUpdater(() => false, preferences);
  assert.equal((await mac.action('check')).canInstall, false);
  await mac.action('releases'); assert.equal(opened, 'https://github.com/pairusuo/multimind-flow/releases');
  Object.defineProperty(process, 'platform', { value: 'win32' });
  release.assets = [];
  assert.equal((await mac.action('check')).canInstall, false, 'Missing metadata falls back to download page');
  release.tag_name = 'v1.1.1'; assert.equal((await mac.action('check')).status, 'current');
} finally { Object.defineProperty(process, 'platform', platform); }
console.log('App update version, download, restart guard and platform fallback tests passed.');
